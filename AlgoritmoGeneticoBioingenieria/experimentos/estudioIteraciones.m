clc;
clear;
close all;

configurarProyecto;

disp('ESTUDIO DEL NUMERO DE ITERACIONES');
disp('=================================');

%% Configuración general

valoresIteraciones = [10 20 30 50 100 150 200];

cantidadEscenarios = length(valoresIteraciones);
cantidadPruebas = 5;

tamanoPoblacion = 20;

probabilidadCruce = 0.90;
probabilidadMutacion = 0.10;

% Mejores métodos del estudio anterior
metodoViajero = 'elitismo';
metodoAckley = 'elitismo';
metodoInventario = 'torneo';

% Ackley
dimensionesAckley = 3;
limitesAckley = [-10 10];
sigmaAckley = 1;
optimoAckley = 3 - exp(1);

% Inventarios
proporcionSigmaInventario = 0.05;

%% Carpeta de resultados

carpetaPrincipal = ...
    fileparts(which('configurarProyecto'));

carpetaResultados = ...
    fullfile(carpetaPrincipal, 'resultados');

if ~exist(carpetaResultados, 'dir')
    mkdir(carpetaResultados);
end

%% Preparar almacenamiento

fitnessViajero = zeros( ...
    cantidadEscenarios, cantidadPruebas);

tiemposViajero = zeros( ...
    cantidadEscenarios, cantidadPruebas);

individuosViajero = cell( ...
    cantidadEscenarios, cantidadPruebas);

fitnessAckleyResultados = zeros( ...
    cantidadEscenarios, cantidadPruebas);

tiemposAckley = zeros( ...
    cantidadEscenarios, cantidadPruebas);

individuosAckley = cell( ...
    cantidadEscenarios, cantidadPruebas);

fitnessInventarioResultados = zeros( ...
    cantidadEscenarios, cantidadPruebas);

tiemposInventario = zeros( ...
    cantidadEscenarios, cantidadPruebas);

individuosInventario = cell( ...
    cantidadEscenarios, cantidadPruebas);

%% 1. VIAJERO

disp(' ');
disp('1. PROBLEMA DEL VIAJERO');
disp('-----------------------');

for escenario = 1:cantidadEscenarios

    iteraciones = valoresIteraciones(escenario);

    fprintf('\nIteraciones: %d\n', iteraciones);

    for prueba = 1:cantidadPruebas

        % La misma prueba utiliza la misma población inicial
        % para todas las cantidades de iteraciones
        rng(400 + prueba);

        [mejorIndividuo, mejorFitness, ~, tiempo] = ...
            algoritmoGeneticoViajero( ...
                tamanoPoblacion, ...
                iteraciones, ...
                metodoViajero, ...
                probabilidadCruce, ...
                probabilidadMutacion ...
            );

        fitnessViajero(escenario, prueba) = ...
            mejorFitness;

        tiemposViajero(escenario, prueba) = ...
            tiempo;

        individuosViajero{escenario, prueba} = ...
            mejorIndividuo;

        fprintf( ...
            'Prueba %d: fitness = %.4f, tiempo = %.4f s\n', ...
            prueba, mejorFitness, tiempo ...
        );
    end
end

%% 2. ACKLEY

disp(' ');
disp('2. FUNCION DE ACKLEY');
disp('--------------------');

for escenario = 1:cantidadEscenarios

    iteraciones = valoresIteraciones(escenario);

    fprintf('\nIteraciones: %d\n', iteraciones);

    for prueba = 1:cantidadPruebas

        rng(500 + prueba);

        [mejorIndividuo, mejorFitness, ~, tiempo] = ...
            algoritmoGeneticoAckley( ...
                tamanoPoblacion, ...
                iteraciones, ...
                dimensionesAckley, ...
                limitesAckley, ...
                metodoAckley, ...
                probabilidadCruce, ...
                probabilidadMutacion, ...
                sigmaAckley ...
            );

        fitnessAckleyResultados(escenario, prueba) = ...
            mejorFitness;

        tiemposAckley(escenario, prueba) = tiempo;

        individuosAckley{escenario, prueba} = ...
            mejorIndividuo;

        fprintf( ...
            'Prueba %d: fitness = %.10f, tiempo = %.4f s\n', ...
            prueba, mejorFitness, tiempo ...
        );
    end
end

%% 3. INVENTARIOS

disp(' ');
disp('3. PROBLEMA DE INVENTARIOS');
disp('--------------------------');

for escenario = 1:cantidadEscenarios

    iteraciones = valoresIteraciones(escenario);

    fprintf('\nIteraciones: %d\n', iteraciones);

    for prueba = 1:cantidadPruebas

        rng(600 + prueba);

        [mejorIndividuo, mejorFitness, ~, tiempo] = ...
            algoritmoGeneticoInventario( ...
                tamanoPoblacion, ...
                iteraciones, ...
                metodoInventario, ...
                probabilidadCruce, ...
                probabilidadMutacion, ...
                proporcionSigmaInventario ...
            );

        fitnessInventarioResultados(escenario, prueba) = ...
            mejorFitness;

        tiemposInventario(escenario, prueba) = ...
            tiempo;

        individuosInventario{escenario, prueba} = ...
            mejorIndividuo;

        fprintf( ...
            'Prueba %d: fitness = %.10f, tiempo = %.4f s\n', ...
            prueba, mejorFitness, tiempo ...
        );
    end
end

%% Calcular indicadores

promedioFitnessViajero = zeros(cantidadEscenarios, 1);
mejorFitnessViajero = zeros(cantidadEscenarios, 1);
desviacionViajero = zeros(cantidadEscenarios, 1);
tiempoPromedioViajero = zeros(cantidadEscenarios, 1);
mejorIndividuoViajero = cell(cantidadEscenarios, 1);

promedioFitnessAckley = zeros(cantidadEscenarios, 1);
mejorFitnessAckley = zeros(cantidadEscenarios, 1);
desviacionAckley = zeros(cantidadEscenarios, 1);
rmseAckley = zeros(cantidadEscenarios, 1);
tiempoPromedioAckley = zeros(cantidadEscenarios, 1);
mejorIndividuoAckley = cell(cantidadEscenarios, 1);

promedioFitnessInventario = zeros(cantidadEscenarios, 1);
mejorFitnessInventario = zeros(cantidadEscenarios, 1);
desviacionInventario = zeros(cantidadEscenarios, 1);
tiempoPromedioInventario = zeros(cantidadEscenarios, 1);
mejorIndividuoInventario = cell(cantidadEscenarios, 1);

for escenario = 1:cantidadEscenarios

    %% Viajero

    resultados = fitnessViajero(escenario, :);

    promedioFitnessViajero(escenario) = mean(resultados);
    desviacionViajero(escenario) = std(resultados);

    [mejorFitnessViajero(escenario), posicion] = ...
        min(resultados);

    mejorIndividuoViajero{escenario} = mat2str( ...
        individuosViajero{escenario, posicion}, 6 ...
    );

    tiempoPromedioViajero(escenario) = ...
        mean(tiemposViajero(escenario, :));

    %% Ackley

    resultados = fitnessAckleyResultados(escenario, :);

    promedioFitnessAckley(escenario) = mean(resultados);
    desviacionAckley(escenario) = std(resultados);

    [mejorFitnessAckley(escenario), posicion] = ...
        min(resultados);

    mejorIndividuoAckley{escenario} = mat2str( ...
        individuosAckley{escenario, posicion}, 6 ...
    );

    rmseAckley(escenario) = sqrt( ...
        mean((resultados - optimoAckley) .^ 2) ...
    );

    tiempoPromedioAckley(escenario) = ...
        mean(tiemposAckley(escenario, :));

    %% Inventarios

    resultados = ...
        fitnessInventarioResultados(escenario, :);

    promedioFitnessInventario(escenario) = ...
        mean(resultados);

    desviacionInventario(escenario) = ...
        std(resultados);

    [mejorFitnessInventario(escenario), posicion] = ...
        min(resultados);

    mejorIndividuoInventario{escenario} = mat2str( ...
        individuosInventario{escenario, posicion}, 6 ...
    );

    tiempoPromedioInventario(escenario) = ...
        mean(tiemposInventario(escenario, :));
end

%% Crear tablas

Iteraciones = valoresIteraciones';

tablaViajero = table( ...
    Iteraciones, ...
    promedioFitnessViajero, ...
    mejorFitnessViajero, ...
    desviacionViajero, ...
    tiempoPromedioViajero, ...
    mejorIndividuoViajero, ...
    'VariableNames', { ...
        'Iteraciones', ...
        'FitnessPromedio', ...
        'MejorFitness', ...
        'DesviacionEstandar', ...
        'TiempoPromedio_s', ...
        'MejorIndividuo' ...
    } ...
);

tablaAckley = table( ...
    Iteraciones, ...
    promedioFitnessAckley, ...
    mejorFitnessAckley, ...
    desviacionAckley, ...
    rmseAckley, ...
    tiempoPromedioAckley, ...
    mejorIndividuoAckley, ...
    'VariableNames', { ...
        'Iteraciones', ...
        'FitnessPromedio', ...
        'MejorFitness', ...
        'DesviacionEstandar', ...
        'RMSE', ...
        'TiempoPromedio_s', ...
        'MejorIndividuo' ...
    } ...
);

tablaInventario = table( ...
    Iteraciones, ...
    promedioFitnessInventario, ...
    mejorFitnessInventario, ...
    desviacionInventario, ...
    tiempoPromedioInventario, ...
    mejorIndividuoInventario, ...
    'VariableNames', { ...
        'Iteraciones', ...
        'FitnessPromedio', ...
        'MejorFitness', ...
        'DesviacionEstandar', ...
        'TiempoPromedio_s', ...
        'MejorIndividuo' ...
    } ...
);

%% Mostrar tablas

disp(' ');
disp('TABLA DE ITERACIONES DEL VIAJERO');
disp(tablaViajero);

disp(' ');
disp('TABLA DE ITERACIONES DE ACKLEY');
disp(tablaAckley);

disp(' ');
