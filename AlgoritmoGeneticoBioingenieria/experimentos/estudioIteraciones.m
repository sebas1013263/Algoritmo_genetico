    ) ...
);

writetable( ...
    tablaAckley, ...
    fullfile( ...
        carpetaResultados, ...
        'iteraciones_ackley.csv' ...
    ) ...
);

writetable( ...
    tablaInventario, ...
    fullfile( ...
        carpetaResultados, ...
        'iteraciones_inventario.csv' ...
    ) ...
);

