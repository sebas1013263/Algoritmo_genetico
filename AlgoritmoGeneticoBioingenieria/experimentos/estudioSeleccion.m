clc;
clear;
close all;

% Configurar carpetas
configurarProyecto;

disp('ESTUDIO DEL MEJOR METODO DE SELECCION');
disp('======================================');

%% Configuración general

metodos = {'elitismo', 'torneo', 'ruleta'};

cantidadMetodos = length(metodos);
cantidadPruebas = 5;

tamanoPoblacion = 20;
numeroGeneraciones = 100;

probabilidadCruce = 0.90;
probabilidadMutacion = 0.10;

% Ackley
dimensionesAckley = 3;
limitesAckley = [-10 10];
sigmaAckley = 1;

% Inventarios
proporcionSigmaInventario = 0.05;

% Óptimo conocido de Ackley
optimoAckley = 3 - exp(1);

%% Ubicación de resultados

carpetaPrincipal = ...
    fileparts(which('configurarProyecto'));

carpetaResultados = ...
    fullfile(carpetaPrincipal, 'resultados');

if ~exist(carpetaResultados, 'dir')
    mkdir(carpetaResultados);
end

%% Matrices para guardar resultados

fitnessViajero = zeros( ...
    cantidadMetodos, cantidadPruebas);

tiemposViajero = zeros( ...
    cantidadMetodos, cantidadPruebas);

individuosViajero = cell( ...
    cantidadMetodos, cantidadPruebas);

fitnessAckleyResultados = zeros( ...
    cantidadMetodos, cantidadPruebas);

tiemposAckley = zeros( ...
    cantidadMetodos, cantidadPruebas);

individuosAckley = cell( ...
    cantidadMetodos, cantidadPruebas);

fitnessInventarioResultados = zeros( ...
    cantidadMetodos, cantidadPruebas);

tiemposInventario = zeros( ...
    cantidadMetodos, cantidadPruebas);

individuosInventario = cell( ...
    cantidadMetodos, cantidadPruebas);

%% 1. EXPERIMENTO DEL VIAJERO

disp(' ');
disp('1. EJECUTANDO PROBLEMA DEL VIAJERO');
disp('----------------------------------');

for metodo = 1:cantidadMetodos

    fprintf('\nMetodo: %s\n', metodos{metodo});

    for prueba = 1:cantidadPruebas

        % Misma semilla para comparar métodos justamente
        rng(100 + prueba);

        [mejorIndividuo, mejorFitness, ~, tiempo] = ...
            algoritmoGeneticoViajero( ...
                tamanoPoblacion, ...
                numeroGeneraciones, ...
                metodos{metodo}, ...
                probabilidadCruce, ...
                probabilidadMutacion ...
            );

        fitnessViajero(metodo, prueba) = ...
            mejorFitness;

        tiemposViajero(metodo, prueba) = ...
            tiempo;

        individuosViajero{metodo, prueba} = ...
            mejorIndividuo;

        fprintf( ...
            'Prueba %d: fitness = %.4f, tiempo = %.4f s\n', ...
            prueba, mejorFitness, tiempo ...
        );
    end
end

%% 2. EXPERIMENTO DE ACKLEY

disp(' ');
disp('2. EJECUTANDO FUNCION DE ACKLEY');
disp('-------------------------------');

for metodo = 1:cantidadMetodos

    fprintf('\nMetodo: %s\n', metodos{metodo});

    for prueba = 1:cantidadPruebas

        rng(200 + prueba);

        [mejorIndividuo, mejorFitness, ~, tiempo] = ...
            algoritmoGeneticoAckley( ...
                tamanoPoblacion, ...
                numeroGeneraciones, ...
                dimensionesAckley, ...
                limitesAckley, ...
                metodos{metodo}, ...
                probabilidadCruce, ...
                probabilidadMutacion, ...
                sigmaAckley ...
            );

        fitnessAckleyResultados(metodo, prueba) = ...
            mejorFitness;

        tiemposAckley(metodo, prueba) = ...
            tiempo;

        individuosAckley{metodo, prueba} = ...
            mejorIndividuo;

        fprintf( ...
            'Prueba %d: fitness = %.10f, tiempo = %.4f s\n', ...
            prueba, mejorFitness, tiempo ...
        );
    end
end

%% 3. EXPERIMENTO DE INVENTARIOS

disp(' ');
disp('3. EJECUTANDO PROBLEMA DE INVENTARIOS');
disp('--------------------------------------');

for metodo = 1:cantidadMetodos

    fprintf('\nMetodo: %s\n', metodos{metodo});

    for prueba = 1:cantidadPruebas

        rng(300 + prueba);

        [mejorIndividuo, mejorFitness, ~, tiempo] = ...
            algoritmoGeneticoInventario( ...
                tamanoPoblacion, ...
                numeroGeneraciones, ...
                metodos{metodo}, ...
                probabilidadCruce, ...
                probabilidadMutacion, ...
                proporcionSigmaInventario ...
            );

        fitnessInventarioResultados(metodo, prueba) = ...
            mejorFitness;

        tiemposInventario(metodo, prueba) = ...
            tiempo;

        individuosInventario{metodo, prueba} = ...
            mejorIndividuo;

        fprintf( ...
            'Prueba %d: fitness = %.10f, tiempo = %.4f s\n', ...
            prueba, mejorFitness, tiempo ...
        );
    end
end

%% CALCULAR INDICADORES DEL VIAJERO

promedioFitnessViajero = zeros(cantidadMetodos, 1);
mejorFitnessViajero = zeros(cantidadMetodos, 1);
desviacionViajero = zeros(cantidadMetodos, 1);
promedioTiempoViajero = zeros(cantidadMetodos, 1);
mejorIndividuoViajero = cell(cantidadMetodos, 1);

for metodo = 1:cantidadMetodos

    promedioFitnessViajero(metodo) = ...
        mean(fitnessViajero(metodo, :));

    [mejorFitnessViajero(metodo), posicion] = ...
        min(fitnessViajero(metodo, :));

    desviacionViajero(metodo) = ...
        std(fitnessViajero(metodo, :));

    promedioTiempoViajero(metodo) = ...
        mean(tiemposViajero(metodo, :));

    mejorIndividuoViajero{metodo} = mat2str( ...
        individuosViajero{metodo, posicion}, 6 ...
    );
end

%% CALCULAR INDICADORES DE ACKLEY

promedioFitnessAckley = zeros(cantidadMetodos, 1);
mejorFitnessAckley = zeros(cantidadMetodos, 1);
desviacionAckley = zeros(cantidadMetodos, 1);
promedioTiempoAckley = zeros(cantidadMetodos, 1);
rmseAckley = zeros(cantidadMetodos, 1);
mejorIndividuoAckley = cell(cantidadMetodos, 1);

for metodo = 1:cantidadMetodos

    resultadosMetodo = ...
        fitnessAckleyResultados(metodo, :);

    promedioFitnessAckley(metodo) = ...
        mean(resultadosMetodo);

    [mejorFitnessAckley(metodo), posicion] = ...
        min(resultadosMetodo);

    desviacionAckley(metodo) = ...
        std(resultadosMetodo);

    promedioTiempoAckley(metodo) = ...
        mean(tiemposAckley(metodo, :));

    rmseAckley(metodo) = sqrt( ...
        mean((resultadosMetodo - optimoAckley) .^ 2) ...
    );

    mejorIndividuoAckley{metodo} = mat2str( ...
        individuosAckley{metodo, posicion}, 6 ...
    );
end

%% CALCULAR INDICADORES DE INVENTARIOS

promedioFitnessInventario = zeros(cantidadMetodos, 1);
mejorFitnessInventario = zeros(cantidadMetodos, 1);
desviacionInventario = zeros(cantidadMetodos, 1);
promedioTiempoInventario = zeros(cantidadMetodos, 1);
mejorIndividuoInventario = cell(cantidadMetodos, 1);

for metodo = 1:cantidadMetodos

    promedioFitnessInventario(metodo) = ...
        mean(fitnessInventarioResultados(metodo, :));

    [mejorFitnessInventario(metodo), posicion] = ...
        min(fitnessInventarioResultados(metodo, :));

    desviacionInventario(metodo) = ...
        std(fitnessInventarioResultados(metodo, :));

    promedioTiempoInventario(metodo) = ...
        mean(tiemposInventario(metodo, :));

    mejorIndividuoInventario{metodo} = mat2str( ...
        individuosInventario{metodo, posicion}, 6 ...
    );
end

%% CREAR LAS TRES TABLAS

Metodo = metodos';

tablaViajero = table( ...
    Metodo, ...
    promedioFitnessViajero, ...
    mejorFitnessViajero, ...
    desviacionViajero, ...
    promedioTiempoViajero, ...
    mejorIndividuoViajero, ...
    'VariableNames', { ...
        'Metodo', ...
        'FitnessPromedio', ...
        'MejorFitness', ...
        'DesviacionEstandar', ...
        'TiempoPromedio_s', ...
        'MejorIndividuo' ...
    } ...
);

tablaAckley = table( ...
    Metodo, ...
    promedioFitnessAckley, ...
    mejorFitnessAckley, ...
    desviacionAckley, ...
    rmseAckley, ...
    promedioTiempoAckley, ...
    mejorIndividuoAckley, ...
    'VariableNames', { ...
        'Metodo', ...
        'FitnessPromedio', ...
        'MejorFitness', ...
        'DesviacionEstandar', ...
        'RMSE', ...
        'TiempoPromedio_s', ...
        'MejorIndividuo' ...
    } ...
);

tablaInventario = table( ...
    Metodo, ...
    promedioFitnessInventario, ...
    mejorFitnessInventario, ...
    desviacionInventario, ...
    promedioTiempoInventario, ...
    mejorIndividuoInventario, ...
    'VariableNames', { ...
        'Metodo', ...
        'FitnessPromedio', ...
        'MejorFitness', ...
        'DesviacionEstandar', ...
        'TiempoPromedio_s', ...
        'MejorIndividuo' ...
    } ...
);

%% MOSTRAR LAS TABLAS

disp(' ');
disp('TABLA DEL VIAJERO');
disp(tablaViajero);

disp(' ');
disp('TABLA DE ACKLEY');
disp(tablaAckley);

disp(' ');
disp('TABLA DE INVENTARIOS');
disp(tablaInventario);

%% IDENTIFICAR LOS MEJORES MÉTODOS

[~, posicionMejorViajero] = ...
    min(promedioFitnessViajero);

[~, posicionMejorAckley] = ...
    min(promedioFitnessAckley);

[~, posicionMejorInventario] = ...
    min(promedioFitnessInventario);

mejorMetodoViajero = ...
    metodos{posicionMejorViajero};

mejorMetodoAckley = ...
    metodos{posicionMejorAckley};

mejorMetodoInventario = ...
    metodos{posicionMejorInventario};

disp(' ');
disp('MEJORES METODOS SEGUN EL FITNESS PROMEDIO');
disp('------------------------------------------');

fprintf('Viajero: %s\n', mejorMetodoViajero);
fprintf('Ackley: %s\n', mejorMetodoAckley);
fprintf('Inventarios: %s\n', mejorMetodoInventario);

%% GUARDAR CSV

writetable( ...
    tablaViajero, ...
    fullfile( ...
        carpetaResultados, ...
        'seleccion_viajero.csv' ...
    ) ...
);

writetable( ...
    tablaAckley, ...
    fullfile( ...
        carpetaResultados, ...
        'seleccion_ackley.csv' ...
    ) ...
);

writetable( ...
    tablaInventario, ...
    fullfile( ...
        carpetaResultados, ...
        'seleccion_inventario.csv' ...
    ) ...
);

%% GUARDAR TODOS LOS DATOS

save( ...
    fullfile( ...
        carpetaResultados, ...
        'estudio_seleccion.mat' ...
    ), ...
    'tablaViajero', ...
    'tablaAckley', ...
    'tablaInventario', ...
    'fitnessViajero', ...
    'fitnessAckleyResultados', ...
    'fitnessInventarioResultados', ...
    'tiemposViajero', ...
    'tiemposAckley', ...
    'tiemposInventario', ...
    'individuosViajero', ...
    'individuosAckley', ...
    'individuosInventario', ...
    'mejorMetodoViajero', ...
    'mejorMetodoAckley', ...
    'mejorMetodoInventario', ...
    'tamanoPoblacion', ...
    'numeroGeneraciones', ...
    'probabilidadCruce', ...
    'probabilidadMutacion', ...
    'sigmaAckley', ...
    'proporcionSigmaInventario' ...
);

disp(' ');
disp('Los resultados fueron guardados correctamente.');