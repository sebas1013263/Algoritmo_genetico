clc;
clear;
close all;

configurarProyecto;

disp('ESTUDIO DEL NUMERO DE DIMENSIONES DE ACKLEY');
disp('============================================');

%% Configuracion general

valoresDimensiones = [2 3 10 20 50 100];
cantidadEscenarios = length(valoresDimensiones);
cantidadPruebas = 5;

tamanoPoblacion = 20;
iteraciones = 200;
limitesAckley = [-10 10];

% Parametros ganadores de los estudios anteriores
metodoSeleccion = 'elitismo';
probabilidadCruce = 0.90;
probabilidadMutacion = 0.30;
sigmaAckley = 0.50;

% Valor optimo teorico de la funcion utilizada en la guia
optimoAckley = 3 - exp(1);

%% Carpeta de resultados

carpetaPrincipal = fileparts(which('configurarProyecto'));
carpetaResultados = fullfile(carpetaPrincipal, 'resultados');

if ~exist(carpetaResultados, 'dir')
    mkdir(carpetaResultados);
end

%% Preparar almacenamiento

fitnessResultados = zeros(cantidadEscenarios, cantidadPruebas);
tiemposResultados = zeros(cantidadEscenarios, cantidadPruebas);
individuosResultados = cell(cantidadEscenarios, cantidadPruebas);

%% Ejecutar pruebas

for escenario = 1:cantidadEscenarios
    dimensiones = valoresDimensiones(escenario);

    fprintf('\nNumero de dimensiones: %d\n', dimensiones);

    for prueba = 1:cantidadPruebas
        % Se usa la misma semilla en cada escenario para que la
        % comparacion entre dimensiones sea reproducible.
        rng(1000 + prueba);

        [mejorIndividuo, mejorFitness, ~, tiempo] = ...
            algoritmoGeneticoAckley( ...
                tamanoPoblacion, ...
                iteraciones, ...
                dimensiones, ...
                limitesAckley, ...
                metodoSeleccion, ...
                probabilidadCruce, ...
                probabilidadMutacion, ...
                sigmaAckley ...
            );

        fitnessResultados(escenario, prueba) = mejorFitness;
        tiemposResultados(escenario, prueba) = tiempo;
        individuosResultados{escenario, prueba} = mejorIndividuo;

        fprintf( ...
            'Prueba %d: fitness = %.10f, tiempo = %.4f s\n', ...
            prueba, mejorFitness, tiempo ...
        );
    end
end

%% Calcular indicadores

fitnessPromedio = zeros(cantidadEscenarios, 1);
mejorFitness = zeros(cantidadEscenarios, 1);
desviacionEstandar = zeros(cantidadEscenarios, 1);
rmse = zeros(cantidadEscenarios, 1);
tiempoPromedio = zeros(cantidadEscenarios, 1);
mejorIndividuo = cell(cantidadEscenarios, 1);

for escenario = 1:cantidadEscenarios
    resultados = fitnessResultados(escenario, :);

    fitnessPromedio(escenario) = mean(resultados);
    desviacionEstandar(escenario) = std(resultados);
    rmse(escenario) = sqrt( ...
        mean((resultados - optimoAckley) .^ 2) ...
    );
    tiempoPromedio(escenario) = ...
        mean(tiemposResultados(escenario, :));

    [mejorFitness(escenario), posicion] = min(resultados);

    mejorIndividuo{escenario} = mat2str( ...
        individuosResultados{escenario, posicion}, 6 ...
    );
end

%% Crear tabla

Dimensiones = valoresDimensiones';

tablaDimensiones = table( ...
    Dimensiones, ...
    fitnessPromedio, ...
    mejorFitness, ...
    desviacionEstandar, ...
    rmse, ...
    tiempoPromedio, ...
    mejorIndividuo, ...
    'VariableNames', { ...
        'Dimensiones', ...
        'FitnessPromedio', ...
        'MejorFitness', ...
        'DesviacionEstandar', ...
        'RMSE', ...
        'TiempoPromedio_s', ...
        'MejorIndividuo' ...
    } ...
);

%% Mostrar y guardar tabla

disp(' ');
disp('TABLA DEL ESTUDIO DE DIMENSIONES DE ACKLEY');
disp(tablaDimensiones);

writetable( ...
    tablaDimensiones, ...
    fullfile(carpetaResultados, 'dimensiones_ackley.csv') ...
);

%% Grafica de calidad y RMSE

figure;

subplot(2, 1, 1);

errorbar( ...
    valoresDimensiones, ...
    fitnessPromedio, ...
    desviacionEstandar, ...
    '-o', ...
    'LineWidth', 1.5 ...
);

hold on;
yline(optimoAckley, '--k', 'Optimo');
hold off;

grid on;
xlabel('Numero de dimensiones');
ylabel('Fitness promedio');
title('Calidad de la solucion segun las dimensiones');

subplot(2, 1, 2);

plot( ...
    valoresDimensiones, ...
    rmse, ...
    '-o', ...
    'LineWidth', 1.5 ...
);

grid on;
xlabel('Numero de dimensiones');
ylabel('RMSE');
title('Error segun las dimensiones');

saveas( ...
    gcf, ...
    fullfile(carpetaResultados, 'dimensiones_ackley.png') ...
);

%% Grafica del tiempo

figure;

plot( ...
    valoresDimensiones, ...
    tiempoPromedio, ...
    '-o', ...
    'LineWidth', 1.5 ...
);

grid on;
xlabel('Numero de dimensiones');
ylabel('Tiempo promedio (s)');
title('Tiempo de ejecucion segun las dimensiones');

saveas( ...
    gcf, ...
    fullfile(carpetaResultados, 'dimensiones_ackley_tiempo.png') ...
);

%% Guardar todos los datos

save( ...
    fullfile(carpetaResultados, 'estudio_dimensiones_ackley.mat'), ...
    'tablaDimensiones', ...
    'fitnessResultados', ...
    'tiemposResultados', ...
    'individuosResultados', ...
    'valoresDimensiones', ...
    'cantidadPruebas', ...
    'tamanoPoblacion', ...
    'iteraciones', ...
    'limitesAckley', ...
    'metodoSeleccion', ...
    'probabilidadCruce', ...
    'probabilidadMutacion', ...
    'sigmaAckley', ...
    'optimoAckley' ...
);

disp(' ');
disp('El estudio de dimensiones finalizo correctamente.');
disp('Los resultados y graficas fueron guardados.');
