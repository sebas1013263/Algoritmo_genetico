clc;
clear;
close all;

configurarProyecto;

disp('ESTUDIO DE LA ESTRATEGIA DE MUTACION');
disp('====================================');

%% Configuracion general

cantidadPruebas = 5;
tamanoPoblacion = 20;
iteraciones = 200;
probabilidadCruce = 0.90;

% Mejores metodos de seleccion obtenidos anteriormente
metodoViajero = 'elitismo';
metodoAckley = 'elitismo';
metodoInventario = 'torneo';

% Probabilidades de mutacion que se evaluaran
probabilidadesMutacion = [0.05 0.10 0.20 0.30];

% Parametros de Ackley
dimensionesAckley = 3;
limitesAckley = [-10 10];
sigmasAckley = [0.10 0.50 1.00 2.00];
optimoAckley = 3 - exp(1);

% Magnitudes relativas de mutacion para inventarios
proporcionesSigmaInventario = [0.01 0.05 0.10 0.20];

%% Carpeta de resultados

carpetaPrincipal = fileparts(which('configurarProyecto'));
carpetaResultados = fullfile(carpetaPrincipal, 'resultados');

if ~exist(carpetaResultados, 'dir')
    mkdir(carpetaResultados);
end

%% 1. Problema del viajero

disp(' ');
disp('1. PROBLEMA DEL VIAJERO');
disp('-----------------------');

cantidadEscenariosViajero = length(probabilidadesMutacion);

fitnessViajero = zeros(cantidadEscenariosViajero, cantidadPruebas);
tiemposViajero = zeros(cantidadEscenariosViajero, cantidadPruebas);
individuosViajero = cell(cantidadEscenariosViajero, cantidadPruebas);

for escenario = 1:cantidadEscenariosViajero
    pm = probabilidadesMutacion(escenario);

    fprintf('\nProbabilidad de mutacion: %.2f\n', pm);

    for prueba = 1:cantidadPruebas
        % Se conserva la misma semilla para comparar justamente.
        rng(700 + prueba);

        [mejorIndividuo, mejorFitness, ~, tiempo] = ...
            algoritmoGeneticoViajero( ...
                tamanoPoblacion, ...
                iteraciones, ...
                metodoViajero, ...
                probabilidadCruce, ...
                pm ...
            );

        fitnessViajero(escenario, prueba) = mejorFitness;
        tiemposViajero(escenario, prueba) = tiempo;
        individuosViajero{escenario, prueba} = mejorIndividuo;

        fprintf( ...
            'Prueba %d: fitness = %.4f, tiempo = %.4f s\n', ...
            prueba, mejorFitness, tiempo ...
        );
    end
end

%% 2. Funcion de Ackley

disp(' ');
disp('2. FUNCION DE ACKLEY');
disp('--------------------');

cantidadEscenariosAckley = ...
    length(probabilidadesMutacion) * length(sigmasAckley);

pmAckley = zeros(cantidadEscenariosAckley, 1);
sigmaAckleyEvaluado = zeros(cantidadEscenariosAckley, 1);
fitnessAckleyResultados = zeros(cantidadEscenariosAckley, cantidadPruebas);
tiemposAckley = zeros(cantidadEscenariosAckley, cantidadPruebas);
individuosAckley = cell(cantidadEscenariosAckley, cantidadPruebas);

escenario = 0;

for indicePm = 1:length(probabilidadesMutacion)
    for indiceSigma = 1:length(sigmasAckley)
        escenario = escenario + 1;

        pm = probabilidadesMutacion(indicePm);
        sigma = sigmasAckley(indiceSigma);

        pmAckley(escenario) = pm;
        sigmaAckleyEvaluado(escenario) = sigma;

        fprintf( ...
            '\nPm = %.2f, sigma = %.2f\n', ...
            pm, sigma ...
        );

        for prueba = 1:cantidadPruebas
            rng(800 + prueba);

            [mejorIndividuo, mejorFitness, ~, tiempo] = ...
                algoritmoGeneticoAckley( ...
                    tamanoPoblacion, ...
                    iteraciones, ...
                    dimensionesAckley, ...
                    limitesAckley, ...
                    metodoAckley, ...
                    probabilidadCruce, ...
                    pm, ...
                    sigma ...
                );

            fitnessAckleyResultados(escenario, prueba) = mejorFitness;
            tiemposAckley(escenario, prueba) = tiempo;
            individuosAckley{escenario, prueba} = mejorIndividuo;

            fprintf( ...
                'Prueba %d: fitness = %.10f, tiempo = %.4f s\n', ...
                prueba, mejorFitness, tiempo ...
            );
        end
    end
end

%% 3. Problema de inventarios

disp(' ');
disp('3. PROBLEMA DE INVENTARIOS');
disp('--------------------------');

cantidadEscenariosInventario = ...
    length(probabilidadesMutacion) * ...
    length(proporcionesSigmaInventario);

pmInventario = zeros(cantidadEscenariosInventario, 1);
sigmaInventarioEvaluado = zeros(cantidadEscenariosInventario, 1);
fitnessInventarioResultados = zeros( ...
    cantidadEscenariosInventario, cantidadPruebas ...
);
tiemposInventario = zeros( ...
    cantidadEscenariosInventario, cantidadPruebas ...
);
individuosInventario = cell( ...
    cantidadEscenariosInventario, cantidadPruebas ...
);

escenario = 0;

for indicePm = 1:length(probabilidadesMutacion)
    for indiceSigma = 1:length(proporcionesSigmaInventario)
        escenario = escenario + 1;

        pm = probabilidadesMutacion(indicePm);
        proporcionSigma = proporcionesSigmaInventario(indiceSigma);

        pmInventario(escenario) = pm;
        sigmaInventarioEvaluado(escenario) = proporcionSigma;

        fprintf( ...
            '\nPm = %.2f, proporcion sigma = %.2f\n', ...
            pm, proporcionSigma ...
        );

        for prueba = 1:cantidadPruebas
            rng(900 + prueba);

            [mejorIndividuo, mejorFitness, ~, tiempo] = ...
                algoritmoGeneticoInventario( ...
                    tamanoPoblacion, ...
                    iteraciones, ...
                    metodoInventario, ...
                    probabilidadCruce, ...
                    pm, ...
                    proporcionSigma ...
                );

            fitnessInventarioResultados(escenario, prueba) = ...
                mejorFitness;
            tiemposInventario(escenario, prueba) = tiempo;
            individuosInventario{escenario, prueba} = mejorIndividuo;

            fprintf( ...
                'Prueba %d: fitness = %.10f, tiempo = %.4f s\n', ...
                prueba, mejorFitness, tiempo ...
            );
        end
    end
end

%% Calcular indicadores del viajero

promedioFitnessViajero = zeros(cantidadEscenariosViajero, 1);
mejorFitnessViajero = zeros(cantidadEscenariosViajero, 1);
desviacionViajero = zeros(cantidadEscenariosViajero, 1);
tiempoPromedioViajero = zeros(cantidadEscenariosViajero, 1);
mejorIndividuoViajero = cell(cantidadEscenariosViajero, 1);

for escenario = 1:cantidadEscenariosViajero
    resultados = fitnessViajero(escenario, :);

    promedioFitnessViajero(escenario) = mean(resultados);
    desviacionViajero(escenario) = std(resultados);
    tiempoPromedioViajero(escenario) = ...
        mean(tiemposViajero(escenario, :));

    [mejorFitnessViajero(escenario), posicion] = min(resultados);
    mejorIndividuoViajero{escenario} = mat2str( ...
        individuosViajero{escenario, posicion}, 6 ...
    );
end

%% Calcular indicadores de Ackley

promedioFitnessAckley = zeros(cantidadEscenariosAckley, 1);
mejorFitnessAckley = zeros(cantidadEscenariosAckley, 1);
desviacionAckley = zeros(cantidadEscenariosAckley, 1);
rmseAckley = zeros(cantidadEscenariosAckley, 1);
tiempoPromedioAckley = zeros(cantidadEscenariosAckley, 1);
mejorIndividuoAckley = cell(cantidadEscenariosAckley, 1);

for escenario = 1:cantidadEscenariosAckley
    resultados = fitnessAckleyResultados(escenario, :);

    promedioFitnessAckley(escenario) = mean(resultados);
    desviacionAckley(escenario) = std(resultados);
    rmseAckley(escenario) = sqrt( ...
        mean((resultados - optimoAckley) .^ 2) ...
    );
    tiempoPromedioAckley(escenario) = ...
        mean(tiemposAckley(escenario, :));

    [mejorFitnessAckley(escenario), posicion] = min(resultados);
    mejorIndividuoAckley{escenario} = mat2str( ...
        individuosAckley{escenario, posicion}, 6 ...
    );
end

%% Calcular indicadores de inventarios

promedioFitnessInventario = zeros(cantidadEscenariosInventario, 1);
mejorFitnessInventario = zeros(cantidadEscenariosInventario, 1);
desviacionInventario = zeros(cantidadEscenariosInventario, 1);
tiempoPromedioInventario = zeros(cantidadEscenariosInventario, 1);
mejorIndividuoInventario = cell(cantidadEscenariosInventario, 1);

for escenario = 1:cantidadEscenariosInventario
    resultados = fitnessInventarioResultados(escenario, :);

    promedioFitnessInventario(escenario) = mean(resultados);
    desviacionInventario(escenario) = std(resultados);
    tiempoPromedioInventario(escenario) = ...
        mean(tiemposInventario(escenario, :));

    [mejorFitnessInventario(escenario), posicion] = min(resultados);
    mejorIndividuoInventario{escenario} = mat2str( ...
        individuosInventario{escenario, posicion}, 6 ...
    );
end

%% Crear tablas

ProbabilidadMutacion = probabilidadesMutacion';

tablaViajero = table( ...
    ProbabilidadMutacion, ...
    promedioFitnessViajero, ...
    mejorFitnessViajero, ...
    desviacionViajero, ...
    tiempoPromedioViajero, ...
    mejorIndividuoViajero, ...
    'VariableNames', { ...
        'ProbabilidadMutacion', ...
        'FitnessPromedio', ...
        'MejorFitness', ...
        'DesviacionEstandar', ...
        'TiempoPromedio_s', ...
        'MejorIndividuo' ...
    } ...
);

ProbabilidadMutacion = pmAckley;
SigmaMutacion = sigmaAckleyEvaluado;

tablaAckley = table( ...
    ProbabilidadMutacion, ...
    SigmaMutacion, ...
    promedioFitnessAckley, ...
    mejorFitnessAckley, ...
    desviacionAckley, ...
    rmseAckley, ...
    tiempoPromedioAckley, ...
    mejorIndividuoAckley, ...
    'VariableNames', { ...
        'ProbabilidadMutacion', ...
        'SigmaMutacion', ...
        'FitnessPromedio', ...
        'MejorFitness', ...
        'DesviacionEstandar', ...
        'RMSE', ...
        'TiempoPromedio_s', ...
        'MejorIndividuo' ...
    } ...
);

ProbabilidadMutacion = pmInventario;
ProporcionSigma = sigmaInventarioEvaluado;

tablaInventario = table( ...
    ProbabilidadMutacion, ...
    ProporcionSigma, ...
    promedioFitnessInventario, ...
    mejorFitnessInventario, ...
    desviacionInventario, ...
    tiempoPromedioInventario, ...
    mejorIndividuoInventario, ...
    'VariableNames', { ...
        'ProbabilidadMutacion', ...
        'ProporcionSigma', ...
        'FitnessPromedio', ...
        'MejorFitness', ...
        'DesviacionEstandar', ...
        'TiempoPromedio_s', ...
        'MejorIndividuo' ...
    } ...
);

%% Mostrar tablas

disp(' ');
disp('TABLA DE MUTACION DEL VIAJERO');
disp(tablaViajero);

disp(' ');
disp('TABLA DE MUTACION DE ACKLEY');
disp(tablaAckley);

disp(' ');
disp('TABLA DE MUTACION DE INVENTARIOS');
disp(tablaInventario);

%% Guardar tablas

writetable( ...
    tablaViajero, ...
    fullfile(carpetaResultados, 'mutacion_viajero.csv') ...
);

writetable( ...
    tablaAckley, ...
    fullfile(carpetaResultados, 'mutacion_ackley.csv') ...
);

writetable( ...
    tablaInventario, ...
    fullfile(carpetaResultados, 'mutacion_inventario.csv') ...
);

%% Grafica del viajero

figure;

errorbar( ...
    probabilidadesMutacion, ...
    promedioFitnessViajero, ...
    desviacionViajero, ...
    '-o', ...
    'LineWidth', 1.5 ...
);

grid on;
xlabel('Probabilidad de mutacion');
ylabel('Fitness promedio');
title('Estudio de mutacion - viajero');

saveas( ...
    gcf, ...
    fullfile(carpetaResultados, 'mutacion_viajero.png') ...
);

%% Graficas de Ackley

figure;

subplot(2, 1, 1);
hold on;

for indiceSigma = 1:length(sigmasAckley)
    posiciones = sigmaAckleyEvaluado == sigmasAckley(indiceSigma);

    plot( ...
        pmAckley(posiciones), ...
        promedioFitnessAckley(posiciones), ...
        '-o', ...
        'LineWidth', 1.5, ...
        'DisplayName', sprintf('sigma = %.2f', sigmasAckley(indiceSigma)) ...
    );
end

yline(optimoAckley, '--k', 'Optimo');
hold off;
grid on;
xlabel('Probabilidad de mutacion');
ylabel('Fitness promedio');
title('Estudio de mutacion - Ackley');
legend('Location', 'best');

subplot(2, 1, 2);
hold on;

for indiceSigma = 1:length(sigmasAckley)
    posiciones = sigmaAckleyEvaluado == sigmasAckley(indiceSigma);

    plot( ...
        pmAckley(posiciones), ...
        rmseAckley(posiciones), ...
        '-o', ...
        'LineWidth', 1.5, ...
        'DisplayName', sprintf('sigma = %.2f', sigmasAckley(indiceSigma)) ...
    );
end

hold off;
grid on;
xlabel('Probabilidad de mutacion');
ylabel('RMSE');
legend('Location', 'best');

saveas( ...
    gcf, ...
    fullfile(carpetaResultados, 'mutacion_ackley.png') ...
);

%% Grafica de inventarios

figure;
hold on;

for indiceSigma = 1:length(proporcionesSigmaInventario)
    posiciones = ...
        sigmaInventarioEvaluado == ...
        proporcionesSigmaInventario(indiceSigma);

    plot( ...
        pmInventario(posiciones), ...
        promedioFitnessInventario(posiciones), ...
        '-o', ...
        'LineWidth', 1.5, ...
        'DisplayName', sprintf( ...
            'proporcion = %.2f', ...
            proporcionesSigmaInventario(indiceSigma) ...
        ) ...
    );
end

hold off;
grid on;
xlabel('Probabilidad de mutacion');
ylabel('Fitness promedio');
title('Estudio de mutacion - inventarios');
legend('Location', 'best');

saveas( ...
    gcf, ...
    fullfile(carpetaResultados, 'mutacion_inventario.png') ...
);

