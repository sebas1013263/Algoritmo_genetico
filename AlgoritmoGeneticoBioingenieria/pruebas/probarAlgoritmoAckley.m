clc;
clear;
close all;

% Configurar las carpetas
configurarProyecto;

disp('PRUEBA DEL ALGORITMO GENETICO DE ACKLEY');
disp('----------------------------------------');

%% Parámetros

tamanoPoblacion = 20;
numeroGeneraciones = 50;
dimensiones = 3;
limites = [-10 10];

probabilidadCruce = 0.90;
probabilidadMutacion = 0.10;
sigmaM = 1;

valorOptimo = 3 - exp(1);

%% ELITISMO

disp(' ');
disp('EJECUCION CON ELITISMO');

rng(12);

[individuoElitismo, fitnessElitismo, ...
 historialElitismo, tiempoElitismo] = ...
    algoritmoGeneticoAckley( ...
        tamanoPoblacion, ...
        numeroGeneraciones, ...
        dimensiones, ...
        limites, ...
        'elitismo', ...
        probabilidadCruce, ...
        probabilidadMutacion, ...
        sigmaM ...
    );

disp('Mejor individuo:');
disp(individuoElitismo);

fprintf('Mejor fitness: %.10f\n', fitnessElitismo);
fprintf('Distancia al optimo: %.10f\n', ...
    abs(fitnessElitismo - valorOptimo));
fprintf('Tiempo: %.6f segundos\n', tiempoElitismo);

%% TORNEO

disp(' ');
disp('EJECUCION CON TORNEO');

rng(12);

[individuoTorneo, fitnessTorneo, ...
 historialTorneo, tiempoTorneo] = ...
    algoritmoGeneticoAckley( ...
        tamanoPoblacion, ...
        numeroGeneraciones, ...
        dimensiones, ...
        limites, ...
        'torneo', ...
        probabilidadCruce, ...
        probabilidadMutacion, ...
        sigmaM ...
    );

disp('Mejor individuo:');
disp(individuoTorneo);

fprintf('Mejor fitness: %.10f\n', fitnessTorneo);
fprintf('Distancia al optimo: %.10f\n', ...
    abs(fitnessTorneo - valorOptimo));
fprintf('Tiempo: %.6f segundos\n', tiempoTorneo);

%% RULETA

disp(' ');
disp('EJECUCION CON RULETA');

rng(12);

[individuoRuleta, fitnessRuleta, ...
 historialRuleta, tiempoRuleta] = ...
    algoritmoGeneticoAckley( ...
        tamanoPoblacion, ...
        numeroGeneraciones, ...
        dimensiones, ...
        limites, ...
        'ruleta', ...
        probabilidadCruce, ...
        probabilidadMutacion, ...
        sigmaM ...
    );

disp('Mejor individuo:');
disp(individuoRuleta);

fprintf('Mejor fitness: %.10f\n', fitnessRuleta);
fprintf('Distancia al optimo: %.10f\n', ...
    abs(fitnessRuleta - valorOptimo));
fprintf('Tiempo: %.6f segundos\n', tiempoRuleta);

%% Verificar los individuos

assert(length(individuoElitismo) == dimensiones, ...
    'El individuo de elitismo tiene dimensiones incorrectas.');

assert(length(individuoTorneo) == dimensiones, ...
    'El individuo de torneo tiene dimensiones incorrectas.');

assert(length(individuoRuleta) == dimensiones, ...
    'El individuo de ruleta tiene dimensiones incorrectas.');

assert(all(individuoElitismo >= limites(1)) && ...
       all(individuoElitismo <= limites(2)), ...
    'El individuo de elitismo salio de los limites.');

assert(all(individuoTorneo >= limites(1)) && ...
       all(individuoTorneo <= limites(2)), ...
    'El individuo de torneo salio de los limites.');

assert(all(individuoRuleta >= limites(1)) && ...
       all(individuoRuleta <= limites(2)), ...
    'El individuo de ruleta salio de los limites.');

%% Verificar que los fitness correspondan

assert(abs( ...
    fitnessAckley(individuoElitismo) - fitnessElitismo) < 1e-10, ...
    'El fitness de elitismo no corresponde.');

assert(abs( ...
    fitnessAckley(individuoTorneo) - fitnessTorneo) < 1e-10, ...
    'El fitness de torneo no corresponde.');

assert(abs( ...
    fitnessAckley(individuoRuleta) - fitnessRuleta) < 1e-10, ...
    'El fitness de ruleta no corresponde.');

%% Verificar los historiales

assert(length(historialElitismo) == ...
       numeroGeneraciones + 1, ...
    'El historial de elitismo tiene tamaño incorrecto.');

assert(length(historialTorneo) == ...
       numeroGeneraciones + 1, ...
    'El historial de torneo tiene tamaño incorrecto.');

assert(length(historialRuleta) == ...
       numeroGeneraciones + 1, ...
    'El historial de ruleta tiene tamaño incorrecto.');

assert(all(diff(historialElitismo) <= 1e-12), ...
    'El historial de elitismo empeoro.');

assert(all(diff(historialTorneo) <= 1e-12), ...
    'El historial de torneo empeoro.');

assert(all(diff(historialRuleta) <= 1e-12), ...
    'El historial de ruleta empeoro.');

%% Graficar la convergencia

generaciones = 0:numeroGeneraciones;

figure;

plot(generaciones, historialElitismo, ...
    'LineWidth', 1.5);

hold on;

plot(generaciones, historialTorneo, ...
    'LineWidth', 1.5);

plot(generaciones, historialRuleta, ...
    'LineWidth', 1.5);

yline(valorOptimo, '--k', 'Óptimo conocido');

hold off;

grid on;

xlabel('Generación');
ylabel('Mejor valor de Ackley');
title('Convergencia del algoritmo genético de Ackley');

legend( ...
    'Elitismo', ...
    'Torneo', ...
    'Ruleta', ...
    'Óptimo', ...
    'Location', 'best' ...
);

disp(' ');
disp('Todas las pruebas del algoritmo de Ackley fueron superadas.');